"""Build Settings → About from package.json, WHATSNEW.md and PRIVACY.md.

Writes app/assets/about.js (the version, both documents as HTML, and the About links) and, when segno is
installed, a QR code for each link in app/assets/about/. The TV has no browser to rely on, so a link is
shown as a code to scan with a phone. Run `npm run build:about` after editing either document or a link;
`npm run check` fails while about.js is out of date. The QR codes only change with the links.
"""
from pathlib import Path
import html
import json
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'app/assets/about.js'
QR_DIR = ROOT / 'app/assets/about'

LINKS = [
    {'id': 'coffee', 'label': 'Buy me a coffee', 'line': 'Support FoyerLauncher with a small donation through PayPal.',
     'url': 'https://www.paypal.com/donate/?business=UKUTJS6BBACUU&no_recurring=0&item_name=Buy+me+a+coffee+%3A%29&currency_code=AUD',
     'shown': 'paypal.com/donate'},
    {'id': 'website', 'label': 'Windows-HQ.com', 'line': 'The developer’s website, with other apps and projects.',
     'url': 'https://windows-hq.com', 'shown': 'windows-hq.com'},
    {'id': 'source', 'label': 'Source code', 'line': 'FoyerLauncher is free software under the GNU GPL. Get the code, report a problem or suggest a change.',
     'url': 'https://github.com/nycoagung/foyerLauncher', 'shown': 'github.com/nycoagung/foyerLauncher'},
]


def inline(text):
    """Escape, then the Markdown the documents use: code, bold, emphasis and links (shown as text)."""
    out, last = [], 0
    for m in re.finditer(r'\[([^\]]+)\]\(([^)\s]+)\)', text):
        out.append(spans(text[last:m.start()]))
        label, url = m.group(1), m.group(2)
        shown = re.sub(r'^https?://(www\.)?', '', url).rstrip('/')
        # A link can't be opened on the TV, so its address is written out unless the label already says it.
        out.append(spans(label) + ('' if label.lower().strip('/') in url.lower() else ' (' + html.escape(shown) + ')'))
        last = m.end()
    out.append(spans(text[last:]))
    return ''.join(out)


def spans(text):
    # Curly apostrophes, like the rest of the interface.
    text = html.escape(text, quote=False).replace("'", '’')
    text = re.sub(r'`([^`]+)`', r'<code>\1</code>', text)
    text = re.sub(r'\*\*([^*]+)\*\*', r'<strong>\1</strong>', text)
    return re.sub(r'(?<![\w])_([^_]+)_(?![\w])', r'<em>\1</em>', text)


def markdown(source):
    """The subset WHATSNEW.md and PRIVACY.md use. The first heading is the page title, so it is left out."""
    out, paragraph, depth = [], [], 0

    def flush():
        if paragraph:
            out.append('<p>' + inline(' '.join(paragraph)) + '</p>')
            paragraph.clear()

    def close_lists(to):
        nonlocal depth
        while depth > to:
            out.append('</li></ul>')
            depth -= 1

    for line in source.splitlines():
        bullet = re.match(r'^( *)- (.*)$', line)
        if bullet:
            flush()
            level = len(bullet.group(1)) // 2 + 1
            if level > depth:
                while depth < level:
                    out.append('<ul><li>')
                    depth += 1
            else:
                close_lists(level)
                out.append('</li><li>')
            out.append(inline(bullet.group(2)))
            continue
        if depth and line.startswith('  ') and line.strip():
            out.append(' ' + inline(line.strip()))
            continue
        close_lists(0)
        if not line.strip() or line.strip() == '---' or line.startswith('# '):
            flush()
        elif line.startswith('### '):
            flush(); out.append('<h4>' + inline(line[4:]) + '</h4>')
        elif line.startswith('## '):
            flush(); out.append('<h3>' + inline(line[3:]) + '</h3>')
        else:
            paragraph.append(line.strip())
    flush()
    close_lists(0)
    return ''.join(out).replace('<ul><li></li><li>', '<ul><li>')


def build():
    version = json.loads((ROOT / 'package.json').read_text(encoding='utf-8'))['version']
    about = {'version': version, 'whatsNew': markdown((ROOT / 'WHATSNEW.md').read_text(encoding='utf-8')),
             'privacy': markdown((ROOT / 'PRIVACY.md').read_text(encoding='utf-8')),
             'links': [{key: link[key] for key in ('id', 'label', 'line', 'shown')} for link in LINKS]}
    return ('/* Settings → About. Generated by scripts/build_about.py from package.json, WHATSNEW.md and PRIVACY.md; do not edit. */\n'
            'window.FoyerAbout = ' + json.dumps(about, ensure_ascii=False, separators=(',', ':')) + ';\n')


def write_codes():
    import segno  # Development only: pip install segno
    QR_DIR.mkdir(exist_ok=True)
    for link in LINKS:
        code = segno.make(link['url'], error='m', micro=False)
        path = QR_DIR / (link['id'] + '.svg')
        code.save(str(path), kind='svg', scale=1, border=0, dark='#1d1a16', light=None, xmldecl=False, svgns=True)
        # A viewBox lets the page draw the code at any size; crisp edges keep the modules square.
        size = code.symbol_size(scale=1, border=0)[0]
        svg = path.read_text(encoding='utf-8').replace('<svg ', '<svg viewBox="0 0 %d %d" shape-rendering="crispEdges" ' % (size, size), 1)
        path.write_text(svg, encoding='utf-8')


if __name__ == '__main__':
    OUTPUT.write_text(build(), encoding='utf-8')
    print('Wrote app/assets/about.js')
    if '--codes' in sys.argv:
        write_codes()
        print('Wrote ' + str(len(LINKS)) + ' QR codes to app/assets/about/')
